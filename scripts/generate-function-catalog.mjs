// Generates the function catalog the isolated SQL suites compare against (CI-01) from a running
// local stack (`supabase start` / `supabase db reset`: baseline + every migration):
//   supabase/generated/function-catalog.json    fingerprint per signature (body hash, interface,
//                                               config, owner, EXECUTE), plus names migrations drop
//   supabase/generated/function-definitions.sql  pg_get_functiondef per signature (installLiveFunction)
//
//   node scripts/generate-function-catalog.mjs --write [--workdir <dir>]
//   node scripts/generate-function-catalog.mjs --check [--workdir <dir>]
//
// Never generate it from production: it describes what the migrations in this repository produce.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { CATALOG_PATH, DEFINITIONS_PATH, DEFINITIONS_SQL, FINGERPRINT_SQL, functionName, lastJsonLine, sortKeys } = require('./lib/live-schema.cjs');
const { POSTGRES_MAJOR } = require('./lib/isolated-postgres.cjs');

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const mode = args.includes('--write') ? 'write' : args.includes('--check') ? 'check' : null;
if (!mode) throw new Error('Usage: generate-function-catalog.mjs --write|--check [--workdir <dir>]');
const workdirIndex = args.indexOf('--workdir');
const workdir = workdirIndex >= 0 ? path.resolve(args[workdirIndex + 1]) : root;

const config = fs.readFileSync(path.join(workdir, 'supabase', 'config.toml'), 'utf8');
const projectId = /^project_id\s*=\s*"([^"]+)"/m.exec(config)?.[1];
const majorVersion = Number(/^\[db\][^[]*?^major_version\s*=\s*(\d+)/m.exec(config)?.[1]);
if (!projectId || !majorVersion) throw new Error(`Cannot read project_id and [db] major_version from ${workdir}/supabase/config.toml`);

function query(sql) {
    const result = spawnSync('docker', ['exec', '-i', '-e', 'PGCLIENTENCODING=UTF8', `supabase_db_${projectId}`,
        'psql', '-X', '-qAt', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1'], {
        input: sql,
        encoding: 'utf8',
        maxBuffer: 256 * 1024 * 1024,
        windowsHide: true,
    });
    if (result.status !== 0) {
        throw new Error(`${result.stderr || result.error?.message || `psql exited with ${result.status}`}\nIs the local stack running (pnpm db:start:check)?`);
    }
    return result.stdout;
}

const serverMajor = Math.floor(Number(query('show server_version_num;').trim()) / 10000);
if (serverMajor !== majorVersion || serverMajor !== POSTGRES_MAJOR) {
    throw new Error(`PostgreSQL majors differ: server ${serverMajor}, config.toml ${majorVersion}, isolated suites ${POSTGRES_MAJOR}`);
}

const functions = sortKeys(lastJsonLine(query(FINGERPRINT_SQL)));
const definitions = lastJsonLine(query(DEFINITIONS_SQL));

// Names a migration drops and the chain no longer has: a suite that still creates one tests dead code.
// Best effort (SQL built inside DO blocks is not seen); it never hides a mismatch.
function droppedNames() {
    const liveNames = new Set(Object.keys(functions).map(functionName));
    const names = new Set();
    const dir = path.join(root, 'supabase', 'migrations');
    for (const file of fs.readdirSync(dir).filter((name) => name.endsWith('.sql'))) {
        const text = fs.readFileSync(path.join(dir, file), 'utf8').toLowerCase().replace(/--[^\n]*/g, '');
        for (const statement of text.matchAll(/drop\s+function\s+(?:if\s+exists\s+)?([^;]+);/g)) {
            let depth = 0;
            let current = '';
            const parts = [];
            for (const char of statement[1]) {
                if (char === '(') depth += 1;
                if (char === ')') depth -= 1;
                if (char === ',' && depth === 0) { parts.push(current); current = ''; continue; }
                current += char;
            }
            parts.push(current);
            for (const part of parts) {
                const match = /^\s*((?:"?[a-z_][a-z0-9_]*"?\.)?"?[a-z_][a-z0-9_]*"?)\s*\(/.exec(part);
                if (!match) continue;
                let name = match[1].replace(/"/g, '');
                if (!name.includes('.')) name = `public.${name}`;
                if (!/^(public|private)\./.test(name) || liveNames.has(name)) continue;
                names.add(name);
            }
        }
    }
    return [...names].sort();
}

const catalog = `${JSON.stringify({ serverVersionMajor: serverMajor, dropped: droppedNames(), functions }, null, 2)}\n`;
const definitionsText = [
    '-- Generated by scripts/generate-function-catalog.mjs from a database built from every migration.',
    '-- Do not edit; run pnpm generate:function-catalog. Used by installLiveFunction in the isolated SQL suites.',
    '',
    ...definitions.map(({ signature, definition }) => `-- signature: ${signature}\n${definition.trimEnd()}\n;\n`),
].join('\n');

const relative = (file) => path.relative(root, file).replace(/\\/g, '/');
if (mode === 'write') {
    fs.mkdirSync(path.dirname(CATALOG_PATH), { recursive: true });
    fs.writeFileSync(CATALOG_PATH, catalog);
    fs.writeFileSync(DEFINITIONS_PATH, definitionsText);
    console.log(`Wrote ${relative(CATALOG_PATH)} and ${relative(DEFINITIONS_PATH)}: ${Object.keys(functions).length} functions, ${JSON.parse(catalog).dropped.length} dropped names.`);
} else {
    const read = (file) => (fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null);
    const currentCatalog = read(CATALOG_PATH);
    const stale = currentCatalog !== catalog || read(DEFINITIONS_PATH) !== definitionsText;
    if (stale) {
        const before = currentCatalog ? JSON.parse(currentCatalog).functions : {};
        const changed = Object.keys(functions).filter((signature) => before[signature] && JSON.stringify(before[signature]) !== JSON.stringify(functions[signature]));
        const added = Object.keys(functions).filter((signature) => !before[signature]);
        const removed = Object.keys(before).filter((signature) => !functions[signature]);
        console.error('The function catalog does not match the migrations. Run: pnpm generate:function-catalog (with the local stack running).');
        for (const [label, list] of [['changed', changed], ['added', added], ['removed', removed]]) {
            if (list.length) console.error(`${label}: ${list.join(', ')}`);
        }
        process.exit(1);
    }
    console.log(`Function catalog matches the migrations: ${Object.keys(functions).length} functions.`);
}
